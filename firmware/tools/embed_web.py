"""Embeds firmware/web/ into the firmware as gzip-compressed byte arrays.

Runs before every chip build (extra_scripts = pre:tools/embed_web.py) and
writes src/web/assets.h, which is generated and not committed.
"""

import gzip
import mimetypes
import os

Import("env")  # noqa: F821  (provided by PlatformIO)

PROJECT = env["PROJECT_DIR"]  # noqa: F821
WEB = os.path.join(PROJECT, "web")
OUT = os.path.join(PROJECT, "src", "web", "assets.h")

TYPES = {".js": "text/javascript", ".json": "application/json", ".webmanifest": "application/manifest+json",
         ".svg": "image/svg+xml"}


def content_type(path):
    ext = os.path.splitext(path)[1]
    return TYPES.get(ext) or mimetypes.guess_type(path)[0] or "application/octet-stream"


def embed():
    files = []
    for root, _, names in os.walk(WEB):
        for name in sorted(names):
            if name.startswith("."):
                continue
            full = os.path.join(root, name)
            files.append(("/" + os.path.relpath(full, WEB).replace(os.sep, "/"), full))
    files.sort()

    lines = [
        "// Generated by tools/embed_web.py from firmware/web/. Do not edit.",
        "#pragma once",
        "#include <stddef.h>",
        "#include <stdint.h>",
        "",
        "struct WebAsset { const char* path; const char* type; const uint8_t* data; size_t size; };",
        "",
    ]
    entries = []
    for i, (url, full) in enumerate(files):
        with open(full, "rb") as f:
            data = gzip.compress(f.read(), compresslevel=9, mtime=0)
        body = ",".join(str(b) for b in data)
        lines.append(f"static const uint8_t kWebAsset{i}[] = {{{body}}};")
        entries.append(f'  {{"{url}", "{content_type(full)}", kWebAsset{i}, sizeof(kWebAsset{i})}},')
    lines += ["", "static const WebAsset kWebAssets[] = {", *entries, "};", ""]

    content = "\n".join(lines)
    if os.path.exists(OUT):
        with open(OUT) as f:
            if f.read() == content:
                return
    with open(OUT, "w") as f:
        f.write(content)
    print(f"Embedded {len(files)} web files into src/web/assets.h")


embed()
